import { readFile, writeFile } from 'node:fs/promises';

// One canonical security implementation, two loader formats:
// Chrome's MV3 module entry imports this generated side effect first;
// Firefox static package executes it before service-worker.js as a script.
const sourceUrl = new URL('../extension/action-binding.mjs', import.meta.url);
const outputUrl = new URL('../extension/action-binding-runtime.js', import.meta.url);
const source = await readFile(sourceUrl, 'utf8');
const classic = source.replace(/^export\s+(?=(?:const|function|async function)\b)/gm, '');
if (/^\s*export\s/m.test(classic)) throw new Error('Action binding has unsupported export form; refusing unsafe generated runtime');
const generated = `// GENERATED by tools/sync-action-binding.mjs; edit action-binding.mjs instead.\n${classic}\nObject.defineProperty(globalThis, 'CAPTAIN_ACTION_BINDING', { value: Object.freeze({ ACTION_BINDING_TTL_MS, validateActionOnDevice, invalidateTaskBinding }), configurable: false, writable: false });\n`;
await writeFile(outputUrl, generated);
